import AppKit
import NearclipKit

/// Watches NSPasteboard for copies made on this Mac and writes clips that arrive from other devices.
@MainActor
final class PasteboardMonitor: ClipboardWriter {
    enum Content {
        case text(String)
        case image(Data, mime: String, width: Int, height: Int)
    }

    static let marker = NSPasteboard.PasteboardType("studio.ivlis.nearclip.marker")
    /// Markers used by password managers and utilities for content that must not be recorded (nspasteboard.org).
    static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "com.typeit4me.clipping",
    ]
    static let imageTypes: Set<NSPasteboard.PasteboardType> = [.png, .tiff, NSPasteboard.PasteboardType("public.jpeg"),
                                                               NSPasteboard.PasteboardType("public.heic")]

    /// NC_PASTEBOARD (development only) points the monitor at a private named pasteboard so automated tests
    /// never touch the user's real clipboard.
    private let pb: NSPasteboard = ProcessInfo.processInfo.environment["NC_PASTEBOARD"].map { NSPasteboard(name: NSPasteboard.Name($0)) } ?? .general
    private let settings: AppSettings
    private var lastChange: Int
    private var timer: Timer?
    private var tiffProvider: TIFFProvider?
    var onCopy: ((Content) -> Void)?
    var onTooLarge: (() -> Void)?

    init(settings: AppSettings) {
        self.settings = settings
        lastChange = 0
        lastChange = pb.changeCount
    }

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        let cc = pb.changeCount
        guard cc != lastChange else { return }
        lastChange = cc
        guard !settings.paused else { return }
        if pb == NSPasteboard.general, MacSystem.clipboardAccess == .denied { return }
        let types = pb.types ?? []
        if types.contains(Self.marker) { return }
        if types.contains(where: { Self.skipTypes.contains($0.rawValue) }) { return }
        if let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier, settings.ignoredApps.contains(app) { return }
        if types.contains(.fileURL) { return }
        if let content = read(types) { onCopy?(content) }
    }

    private func read(_ types: [NSPasteboard.PasteboardType]) -> Content? {
        let imageFirst = types.first.map { Self.imageTypes.contains($0) } ?? false
        if imageFirst || !types.contains(.string), types.contains(where: { Self.imageTypes.contains($0) }) {
            if let image = readImage() { return image }
        }
        if let s = pb.string(forType: .string), !s.isEmpty { return .text(s) }
        return nil
    }

    private func readImage() -> Content? {
        var data: Data?
        var mime = "image/png"
        if let png = pb.data(forType: .png) {
            data = png
        } else if let raw = pb.data(forType: .tiff) ?? pb.data(forType: NSPasteboard.PasteboardType("public.heic")),
                  let rep = NSBitmapImageRep(data: raw) {
            data = rep.representation(using: .png, properties: [:])
        } else if let jpeg = pb.data(forType: NSPasteboard.PasteboardType("public.jpeg")) {
            data = jpeg
            mime = "image/jpeg"
        }
        guard var out = data, let rep = NSBitmapImageRep(data: out) else { return nil }
        let limit = 32 * 1_048_576
        if out.count > limit {
            guard let jpeg = rep.representation(using: .jpeg, properties: [.compressionFactor: 0.9]), jpeg.count <= limit else {
                onTooLarge?()
                return nil
            }
            out = jpeg
            mime = "image/jpeg"
        }
        return .image(out, mime: mime, width: rep.pixelsWide, height: rep.pixelsHigh)
    }

    // MARK: ClipboardWriter

    func write(_ clip: Clip, blob: Data?) {
        let item = NSPasteboardItem()
        if clip.isImage, let blob {
            if clip.mime == "image/jpeg" {
                item.setData(blob, forType: NSPasteboard.PasteboardType("public.jpeg"))
            } else {
                item.setData(blob, forType: .png)
            }
            // Older apps only read TIFF; render it lazily instead of up front.
            let provider = TIFFProvider(source: blob)
            item.setDataProvider(provider, forTypes: [.tiff])
            tiffProvider = provider
        } else if let text = clip.text {
            item.setString(text, forType: .string)
        } else {
            return
        }
        item.setData(Data(), forType: Self.marker)
        pb.clearContents()
        pb.writeObjects([item])
        lastChange = pb.changeCount
    }
}

private final class TIFFProvider: NSObject, NSPasteboardItemDataProvider {
    let source: Data
    init(source: Data) { self.source = source }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        if type == .tiff, let rep = NSBitmapImageRep(data: source), let tiff = rep.tiffRepresentation {
            item.setData(tiff, forType: .tiff)
        }
    }
}

