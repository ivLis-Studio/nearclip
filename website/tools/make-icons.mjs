// Writes public/assets/js/icons.js: the Lucide icons the site uses (ISC License, https://lucide.dev), inner SVG only.
//   npm install && node tools/make-icons.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const dir = path.join(path.dirname(require.resolve("lucide-static/package.json")), "icons");
const NAMES = [
  "download", "play", "pause", "volume-2", "globe", "code", "check", "arrow-right", "arrow-up-right", "sparkles", "laptop", "monitor",
  "smartphone", "tablet-smartphone", "wifi", "earth", "lock", "shield-check", "key-round", "qr-code", "history", "search", "pin", "image",
  "link", "type", "palette", "clipboard", "clipboard-copy", "clipboard-paste", "send", "zap", "refresh-cw", "eye-off", "circle-pause",
  "keyboard", "languages", "sun-moon", "server-off", "user-round-x", "waypoints", "trash-2", "hash", "file-text", "external-link",
  "book-open", "command", "bell", "route", "house", "signal", "circle-check", "info", "package", "terminal", "scan-line", "hand",
  "shopping-bag", "message-square-text",
];
const out = {};
for (const n of NAMES) {
  const svg = fs.readFileSync(path.join(dir, n + ".svg"), "utf8");
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*\n\s*/g, " ").trim();
}
const version = require("lucide-static/package.json").version;
const js = "// Lucide icons " + version + " (ISC License, https://lucide.dev). Generated by tools/make-icons.mjs.\nwindow.ICONS = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(path.join(here, "../public/assets/js/icons.js"), js);
console.log("icons.js:", NAMES.length, "icons,", js.length, "bytes");

